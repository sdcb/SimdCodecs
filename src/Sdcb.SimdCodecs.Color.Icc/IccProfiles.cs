using System;
using System.Buffers.Binary;
using System.Reflection;
using System.Security.Cryptography;
using System.Text;
using Sdcb.SimdCodecs.Abstractions;

namespace Sdcb.SimdCodecs.Color.Icc;

/// <summary>
/// Bundled ICC profiles. Callers that want their TIFF / PNG output to
/// round-trip through colour-managed viewers (PixInsight, Lightroom, browsers)
/// without supplying their own profile bytes can pass one of these directly
/// to <c>Sdcb.SimdCodecs.Tiff.TiffPageOptions.IccProfile</c> or to the
/// <c>Sdcb.SimdCodecs.Png.PngWriter.Encode(..., iccProfile)</c> overload.
///
/// The bundled sRGB profile is a 588-byte v4 profile generated by LittleCMS
/// (the same engine that ships in Pillow / GIMP / Krita). v4 is the modern
/// recommended encoding from the ICC and is round-tripped correctly by every
/// major image library; the binary blob lives at <c>sRGB-v4.icc</c> alongside
/// this source file and is loaded lazily on first access.
/// </summary>
public static class IccProfiles
{
    private static readonly Lazy<byte[]> _sRgbV4 = new(() => LoadEmbeddedResource("Sdcb.SimdCodecs.Color.Icc.sRGB-v4.icc"));

    /// <summary>
    /// sRGB IEC61966-2.1 v4 ICC profile (588 bytes). Public domain — generated
    /// by LittleCMS. Use this when writing colour-managed output that should be
    /// interpreted as sRGB by downstream readers.
    /// </summary>
    public static ReadOnlyMemory<byte> SRgbV4 => _sRgbV4.Value;

    /// <summary>
    /// The profile's description: its <c>desc</c> tag, the name a colour-managed application shows
    /// ("sRGB IEC61966-2.1", "Display P3"). A v2 profile stores it as <c>textDescriptionType</c>
    /// (7-bit ASCII); a v4 profile as <c>multiLocalizedUnicodeType</c> (UTF-16BE records per language),
    /// from which the en-US record is taken, else the first English one, else the first. Trailing NULs
    /// and whitespace are trimmed.
    /// </summary>
    /// <param name="profile">A complete ICC profile, e.g. <c>IDecodedImage.IccProfile</c>. Untrusted
    /// input is fine: every offset is checked against the bytes given.</param>
    /// <returns>The description, or null when the profile is malformed, has no <c>desc</c> tag, or
    /// stores it in another type.</returns>
    public static string? Describe(ReadOnlySpan<byte> profile)
    {
        if (!TryFindTag(profile, "desc"u8, out var tag))
            return null;
        if (tag.StartsWith("desc"u8))
            return TextDescription(tag);
        if (tag.StartsWith("mluc"u8))
            return MultiLocalized(tag);
        return null;
    }

    /// <summary>
    /// The H.273 colour primaries an RGB profile declares, when they are ones H.273 names: BT.709 /
    /// sRGB, Display P3 or BT.2020. A <c>cicp</c> tag (ICC v4.4) is taken as it stands. Otherwise the
    /// matrix colorants (<c>rXYZ</c>, <c>gXYZ</c>, <c>bXYZ</c>) are compared with each standard's
    /// primaries and D65 white adapted to the D50 connection space by the Bradford transform (ICC.1
    /// Annex E), within 0.004 per component: enough for the rounding of real profiles, far tighter
    /// than the distance between the gamuts.
    /// </summary>
    /// <param name="profile">A complete ICC profile. Untrusted input is fine.</param>
    /// <param name="primaries">The primaries, or <see cref="ColorPrimaries.Unspecified"/> on false.</param>
    /// <returns>False when the profile is malformed, not RGB, a LUT-based profile without colorants, or
    /// declares other primaries (Adobe RGB, ProPhoto, a camera's or a display's own).</returns>
    public static bool TryGetPrimaries(ReadOnlySpan<byte> profile, out ColorPrimaries primaries)
    {
        primaries = ColorPrimaries.Unspecified;
        if (profile.Length < 132 || !profile.Slice(16, 4).SequenceEqual("RGB "u8))
            return false;

        // cicp: type, reserved, then primaries, transfer, matrix and range, one byte each.
        if (TryFindTag(profile, "cicp"u8, out var cicp) && cicp.Length >= 12 && cicp.StartsWith("cicp"u8))
        {
            primaries = (ColorPrimaries)cicp[8];
            return primaries != ColorPrimaries.Unspecified;
        }

        Span<double> colorants = stackalloc double[9];
        if (!TryReadXyz(profile, "rXYZ"u8, colorants[..3]) || !TryReadXyz(profile, "gXYZ"u8, colorants.Slice(3, 3))
            || !TryReadXyz(profile, "bXYZ"u8, colorants.Slice(6, 3)))
            return false;

        foreach (var (candidate, reference) in _knownColorants.Value)
        {
            var match = true;
            for (var i = 0; i < 9 && match; i++)
                match = Math.Abs(colorants[i] - reference[i]) <= 0.004;
            if (match)
            {
                primaries = candidate;
                return true;
            }
        }

        return false;
    }

    // The first tag table entry with this signature, bounds-checked against the profile: header
    // (128 bytes), the tag count, then 12-byte entries of signature, offset and size.
    private static bool TryFindTag(ReadOnlySpan<byte> profile, ReadOnlySpan<byte> signature, out ReadOnlySpan<byte> tag)
    {
        tag = default;
        if (profile.Length < 132)
            return false;
        var count = BinaryPrimitives.ReadUInt32BigEndian(profile[128..]);
        for (long i = 0, entry = 132; i < count && entry + 12 <= profile.Length; i++, entry += 12)
        {
            var e = profile.Slice((int)entry, 12);
            if (!e[..4].SequenceEqual(signature))
                continue;
            var offset = BinaryPrimitives.ReadUInt32BigEndian(e[4..]);
            var size = BinaryPrimitives.ReadUInt32BigEndian(e[8..]);
            if (offset > (uint)profile.Length || size > (uint)profile.Length - offset)
                return false;
            tag = profile.Slice((int)offset, (int)size);
            return true;
        }

        return false;
    }

    // XYZType: 'XYZ ', reserved, then X, Y, Z as s15Fixed16Number.
    private static bool TryReadXyz(ReadOnlySpan<byte> profile, ReadOnlySpan<byte> signature, Span<double> xyz)
    {
        if (!TryFindTag(profile, signature, out var tag) || tag.Length < 20 || !tag.StartsWith("XYZ "u8))
            return false;
        for (var i = 0; i < 3; i++)
            xyz[i] = BinaryPrimitives.ReadInt32BigEndian(tag[(8 + 4 * i)..]) / 65536.0;
        return true;
    }

    // Each standard's colorants as an ICC profile stores them: the RGB-to-XYZ columns for its
    // primaries and D65 white, Bradford-adapted to the D50 PCS white (0.9642, 1, 0.8249).
    private static readonly Lazy<(ColorPrimaries, double[])[]> _knownColorants = new(() =>
    [
        (ColorPrimaries.BT709, Colorants(0.640, 0.330, 0.300, 0.600, 0.150, 0.060)),
        (ColorPrimaries.DisplayP3, Colorants(0.680, 0.320, 0.265, 0.690, 0.150, 0.060)),
        (ColorPrimaries.BT2020, Colorants(0.708, 0.292, 0.170, 0.797, 0.131, 0.046)),
    ]);

    private static double[] Colorants(double rx, double ry, double gx, double gy, double bx, double by)
    {
        // RGB-to-XYZ: the primaries' XYZ (Y = 1) scaled so that RGB (1, 1, 1) is the D65 white.
        double[] white = [0.3127 / 0.3290, 1, (1 - 0.3127 - 0.3290) / 0.3290];
        double[,] p =
        {
            { rx / ry, gx / gy, bx / by },
            { 1, 1, 1 },
            { (1 - rx - ry) / ry, (1 - gx - gy) / gy, (1 - bx - by) / by },
        };
        var s = Solve(p, white);
        var rgbToXyz = new double[3, 3];
        for (var r = 0; r < 3; r++)
            for (var c = 0; c < 3; c++)
                rgbToXyz[r, c] = p[r, c] * s[c];

        // Bradford: to cone space, scale D65 to D50, back.
        double[,] m = { { 0.8951, 0.2664, -0.1614 }, { -0.7502, 1.7135, 0.0367 }, { 0.0389, -0.0685, 1.0296 } };
        double[] d50 = [0.9642, 1, 0.8249];
        var src = Multiply(m, white);
        var dst = Multiply(m, d50);
        var adapt = new double[3, 3];
        var inverse = Invert(m);
        for (var r = 0; r < 3; r++)
            for (var c = 0; c < 3; c++)
                for (var k = 0; k < 3; k++)
                    adapt[r, c] += inverse[r, k] * (dst[k] / src[k]) * m[k, c];

        var result = new double[9];
        for (var column = 0; column < 3; column++)
            for (var row = 0; row < 3; row++)
                for (var k = 0; k < 3; k++)
                    result[column * 3 + row] += adapt[row, k] * rgbToXyz[k, column];
        return result;
    }

    private static double[] Multiply(double[,] m, double[] v) =>
        [m[0, 0] * v[0] + m[0, 1] * v[1] + m[0, 2] * v[2],
         m[1, 0] * v[0] + m[1, 1] * v[1] + m[1, 2] * v[2],
         m[2, 0] * v[0] + m[2, 1] * v[1] + m[2, 2] * v[2]];

    private static double[] Solve(double[,] m, double[] v) => Multiply(Invert(m), v);

    private static double[,] Invert(double[,] m)
    {
        var det = m[0, 0] * (m[1, 1] * m[2, 2] - m[1, 2] * m[2, 1])
                - m[0, 1] * (m[1, 0] * m[2, 2] - m[1, 2] * m[2, 0])
                + m[0, 2] * (m[1, 0] * m[2, 1] - m[1, 1] * m[2, 0]);
        var r = new double[3, 3];
        r[0, 0] = (m[1, 1] * m[2, 2] - m[1, 2] * m[2, 1]) / det;
        r[0, 1] = (m[0, 2] * m[2, 1] - m[0, 1] * m[2, 2]) / det;
        r[0, 2] = (m[0, 1] * m[1, 2] - m[0, 2] * m[1, 1]) / det;
        r[1, 0] = (m[1, 2] * m[2, 0] - m[1, 0] * m[2, 2]) / det;
        r[1, 1] = (m[0, 0] * m[2, 2] - m[0, 2] * m[2, 0]) / det;
        r[1, 2] = (m[0, 2] * m[1, 0] - m[0, 0] * m[1, 2]) / det;
        r[2, 0] = (m[1, 0] * m[2, 1] - m[1, 1] * m[2, 0]) / det;
        r[2, 1] = (m[0, 1] * m[2, 0] - m[0, 0] * m[2, 1]) / det;
        r[2, 2] = (m[0, 0] * m[1, 1] - m[0, 1] * m[1, 0]) / det;
        return r;
    }

    // textDescriptionType (ICC.1:2001): 'desc', reserved, ASCII count (including the NUL), ASCII.
    private static string? TextDescription(ReadOnlySpan<byte> tag)
    {
        if (tag.Length < 12)
            return null;
        var count = BinaryPrimitives.ReadUInt32BigEndian(tag[8..]);
        if (count > (uint)(tag.Length - 12))
            return null;
        return Clean(Encoding.ASCII.GetString(tag.Slice(12, (int)count)));
    }

    // multiLocalizedUnicodeType (ICC.1:2010 10.15): 'mluc', reserved, record count, record size (12),
    // then records of language, country, length and offset, the offset counted from the tag's start.
    private static string? MultiLocalized(ReadOnlySpan<byte> tag)
    {
        if (tag.Length < 16)
            return null;
        var records = BinaryPrimitives.ReadUInt32BigEndian(tag[8..]);
        var recordSize = BinaryPrimitives.ReadUInt32BigEndian(tag[12..]);
        if (recordSize < 12 || records == 0 || records > (uint)(tag.Length - 16) / recordSize)
            return null;

        var best = -1;
        var bestRank = int.MaxValue;
        for (var r = 0; r < (int)records; r++)
        {
            var record = tag.Slice(16 + r * (int)recordSize, 12);
            var rank = record[..2].SequenceEqual("en"u8) ? (record.Slice(2, 2).SequenceEqual("US"u8) ? 0 : 1) : 2;
            if (rank < bestRank)
                (best, bestRank) = (r, rank);
        }

        var chosen = tag.Slice(16 + best * (int)recordSize, 12);
        var length = BinaryPrimitives.ReadUInt32BigEndian(chosen[4..]);
        var offset = BinaryPrimitives.ReadUInt32BigEndian(chosen[8..]);
        if (offset > (uint)tag.Length || length > (uint)tag.Length - offset || length % 2 != 0)
            return null;
        return Clean(Encoding.BigEndianUnicode.GetString(tag.Slice((int)offset, (int)length)));
    }

    private static string? Clean(string text)
    {
        var end = text.IndexOf('\0');
        var trimmed = (end >= 0 ? text[..end] : text).Trim();
        return trimmed.Length == 0 ? null : trimmed;
    }

    private static byte[] LoadEmbeddedResource(string logicalName)
    {
        var asm = typeof(IccProfiles).Assembly;
        using var stream = asm.GetManifestResourceStream(logicalName)
            ?? throw new InvalidOperationException($"Embedded resource '{logicalName}' not found in {asm.GetName().Name}.");
        using var ms = new MemoryStream(capacity: (int)stream.Length);
        stream.CopyTo(ms);
        return ms.ToArray();
    }

    /// <summary>
    /// Returns a copy of <paramref name="baseProfile"/> with an ICC v4.4
    /// <c>cicp</c> tag injected. Use this to layer H.273 colour-space
    /// signalling onto an existing ICC profile so HDR-aware readers
    /// (PixInsight, Affinity, recent Photoshop / ImageMagick) interpret
    /// the embedded file as wide-gamut / HDR, while readers that don't
    /// recognise the tag fall back to the profile body's curves + matrix.
    /// </summary>
    /// <param name="baseProfile">A complete ICC profile (header + tag
    /// table + tag data). Most callers pass <see cref="SRgbV4"/>.Span.</param>
    /// <param name="primaries">H.273 colour primaries codepoint.</param>
    /// <param name="transfer">H.273 transfer function codepoint.</param>
    /// <param name="matrix">H.273 matrix coefficients. ICC v4.4 / PNG-3
    /// both require <see cref="MatrixCoefficients.Identity"/> for image
    /// files; defaults to that.</param>
    /// <param name="videoFullRange">Full-range (true) vs limited-range
    /// (false). PNG-3 requires full range; defaults to true.</param>
    /// <returns>A new ICC profile byte array containing the original
    /// tags plus a <c>cicp</c> tag, with the Profile ID (header MD5)
    /// recomputed per ICC v4 §7.2.18.</returns>
    /// <remarks>
    /// Layout transformation: the new tag table is one entry longer than
    /// the original (12 bytes), so all existing tag-body data is shifted
    /// down by 12 bytes and each existing tag-table entry's offset field
    /// is incremented by 12. The cicp tag body (12 bytes: 4-byte 'cicp'
    /// type signature, 4 reserved zeros, then the 4 H.273 codepoints) is
    /// appended at the end. Profile size in the header (bytes 0..3) is
    /// updated to <c>original_size + 24</c>. The Profile ID MD5 in
    /// header bytes 84..99 is recomputed over the full profile bytes
    /// with bytes 44..47 (profile flags), 64..67 (rendering intent),
    /// and 84..99 (the Profile ID itself) zeroed for the hash, per
    /// ICC v4 §7.2.18.
    /// </remarks>
    public static byte[] WithCicp(
        ReadOnlySpan<byte> baseProfile,
        ColorPrimaries primaries,
        TransferFunction transfer,
        MatrixCoefficients matrix = MatrixCoefficients.Identity,
        bool videoFullRange = true)
    {
        if (baseProfile.Length < 132)
            throw new ArgumentException($"ICC profile too short ({baseProfile.Length} bytes); minimum is 128-byte header + 4-byte tag count.", nameof(baseProfile));

        var declaredSize = (int)BinaryPrimitives.ReadUInt32BigEndian(baseProfile);
        if (declaredSize != baseProfile.Length)
            throw new ArgumentException($"ICC profile size mismatch: header says {declaredSize}, buffer is {baseProfile.Length}.", nameof(baseProfile));

        var tagCount = BinaryPrimitives.ReadUInt32BigEndian(baseProfile[128..]);
        var tagTableEnd = 132 + (int)tagCount * 12;
        if (tagTableEnd > baseProfile.Length)
            throw new ArgumentException($"ICC profile tag table claims {tagCount} entries but body is too short.", nameof(baseProfile));

        // New buffer: original size + 12 bytes (one new tag-table entry)
        // + 12 bytes (the cicp tag body).
        var newSize = baseProfile.Length + 24;
        var result = new byte[newSize];

        // Copy header (0..127) verbatim.
        baseProfile[..128].CopyTo(result);
        // Copy tag count: incremented by 1.
        BinaryPrimitives.WriteUInt32BigEndian(result.AsSpan(128), tagCount + 1);
        // Copy existing tag-table entries (each 12 bytes) and bump each
        // entry's offset field by 12 (their tag bodies shift down to make
        // room for the new entry slot at the end of the table).
        for (var i = 0; i < tagCount; i++)
        {
            var srcEntry = baseProfile.Slice(132 + i * 12, 12);
            var dstEntry = result.AsSpan(132 + i * 12, 12);
            srcEntry.CopyTo(dstEntry);
            var oldOffset = BinaryPrimitives.ReadUInt32BigEndian(dstEntry[4..]);
            BinaryPrimitives.WriteUInt32BigEndian(dstEntry[4..], oldOffset + 12);
        }

        // Position for the NEW cicp tag-table entry: right after the
        // existing ones, still inside the (now larger) tag table.
        var newEntryOffset = 132 + (int)tagCount * 12;
        // Position for the NEW cicp tag body: at the very end. Existing
        // bodies sit between [oldTagTableEnd + 12, newSize - 12).
        var newTagBodyOffset = newSize - 12;

        // Write the new tag-table entry: 4-byte 'cicp' signature, 4-byte
        // offset to body, 4-byte body size.
        WriteSignature(result.AsSpan(newEntryOffset, 4), "cicp"u8);
        BinaryPrimitives.WriteUInt32BigEndian(result.AsSpan(newEntryOffset + 4), (uint)newTagBodyOffset);
        BinaryPrimitives.WriteUInt32BigEndian(result.AsSpan(newEntryOffset + 8), 12u);

        // Copy existing tag bodies forward by 12 bytes (they sat at
        // [old tagTableEnd, declaredSize); they now sit at
        // [new tagTableEnd, declaredSize + 12)). The new tag table is
        // 12 bytes larger so newTagTableEnd == old tagTableEnd + 12.
        baseProfile[tagTableEnd..].CopyTo(result.AsSpan(tagTableEnd + 12));

        // Write the new cicp tag body (12 bytes).
        WriteSignature(result.AsSpan(newTagBodyOffset, 4), "cicp"u8);
        // bytes 4..7: reserved zeros (already zero from `new byte[]`)
        result[newTagBodyOffset + 8] = (byte)primaries;
        result[newTagBodyOffset + 9] = (byte)transfer;
        result[newTagBodyOffset + 10] = (byte)matrix;
        result[newTagBodyOffset + 11] = (byte)(videoFullRange ? 1 : 0);

        // Update the profile size field in the header.
        BinaryPrimitives.WriteUInt32BigEndian(result, (uint)newSize);

        // Recompute the Profile ID MD5 per ICC v4 §7.2.18. The hash
        // covers the entire profile with three header fields zeroed:
        // flags (44..47), rendering intent (64..67), and Profile ID
        // itself (84..99). Save and restore.
        Span<byte> savedFlags = stackalloc byte[4];
        Span<byte> savedIntent = stackalloc byte[4];
        Span<byte> savedId = stackalloc byte[16];
        result.AsSpan(44, 4).CopyTo(savedFlags);
        result.AsSpan(64, 4).CopyTo(savedIntent);
        result.AsSpan(84, 16).CopyTo(savedId);
        result.AsSpan(44, 4).Clear();
        result.AsSpan(64, 4).Clear();
        result.AsSpan(84, 16).Clear();

        Span<byte> md5 = stackalloc byte[16];
        MD5.HashData(result, md5);

        savedFlags.CopyTo(result.AsSpan(44, 4));
        savedIntent.CopyTo(result.AsSpan(64, 4));
        md5.CopyTo(result.AsSpan(84, 16));

        return result;
    }

    private static void WriteSignature(Span<byte> dst, ReadOnlySpan<byte> sig)
    {
        // 4-byte signature literal (e.g. "cicp"u8). Spec stores these as
        // raw ASCII in the file, NOT byte-swapped on either endian.
        sig.CopyTo(dst);
    }
}
